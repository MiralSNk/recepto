-- "Цена (основная)" как отдельное поле убрана из системы полностью —
-- price_day теперь единственная цена номера везде в приложении (типы,
-- админка, публичный API, ИИ-чат). Миграция 013 синхронизировала price
-- ИЗ price_day для уже разошедшихся номеров, но не покрывала обратный
-- случай: номер, у которого price_day вообще никогда не заполнялся
-- (создан ещё до появления этого поля, редактировался только через старую
-- "Цена (основная)"). Без этой миграции у таких номеров price_day остался
-- бы NULL, хотя тип Room.price_day теперь считается везде гарантированно
-- заполненным (маппер подстраховывается через price ?? price_day, но
-- лучше не оставлять реальные данные в противоречии с этим инвариантом).
UPDATE rooms
SET price_day = price
WHERE price_day IS NULL;
