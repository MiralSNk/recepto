-- price и price_day редактировались в админке как два независимых поля
-- ("Цена (основная)" и "Цена за сутки"), хотя должны быть одним и тем же
-- числом — из-за этого один и тот же номер мог показывать гостю разную
-- цену на главной (price) и на странице номера/в форме бронирования/
-- ИИ-помощнику (price_day). Форма больше не даёт их развести (см. коммит
-- с фиксом RoomFormModal.tsx/API), но уже сохранённые номера могли успеть
-- разъехаться раньше — приводим их в порядок один раз при деплое.
UPDATE rooms
SET price = price_day
WHERE price_day IS NOT NULL
  AND price_day <> price;
