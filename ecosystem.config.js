// Конфиг pm2 для продакшена. Сервер маленький (823 МБ RAM всего, MySQL на
// том же боксе) — раньше процесс запускался прямой командой без каких-либо
// защит по памяти и без живучих настроек перезапуска: при быстрой серии
// падений pm2 по умолчанию сдаётся после ~16 попыток и зависает в статусе
// errored (нужен ручной pm2 restart), а сам Node-процесс мог неограниченно
// раздуваться, пока его не убьёт OOM-killer ядра — резко и без разбора
// (заодно рискуя утащить за собой MySQL на том же сервере).
module.exports = {
  apps: [
    {
      name: 'recepto',
      script: 'pnpm',
      args: 'start',
      // Сколько раз подряд можно упасть "нестабильно" (быстрее min_uptime),
      // прежде чем pm2 перестанет пытаться перезапускать сам (дефолт — 16).
      max_restarts: 50,
      // Через сколько мс работы без падения попытка считается "стабильной"
      // и счётчик max_restarts сбрасывается (дефолт — 1000мс).
      min_uptime: 10000,
      // Экспоненциально растущая пауза между перезапусками при повторных
      // падениях (100мс, 200мс, 400мс... до потолка) — не долбит перезапуск
      // мгновенно раз за разом, если проблема не мгновенно решается сама.
      exp_backoff_restart_delay: 3000,
      // Контролируемый упреждающий перезапуск САМИМ pm2, если процесс
      // раздулся — вместо непредсказуемого OOM-killer'а ядра, который может
      // выбрать не тот процесс (например MySQL) на общем маленьком сервере.
      max_memory_restart: '450M',
      // Внутренний потолок V8-кучи самого Node — мягкая защита изнутри
      // (обычная сборка мусора под давлением), которая срабатывает раньше
      // и аккуратнее, чем внешний max_memory_restart по RSS.
      node_args: '--max-old-space-size=384',
      env: {
        NODE_ENV: 'production',
      },
    },
  ],
};
