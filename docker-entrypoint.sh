#!/bin/sh
# Запускается при каждом старте контейнера (включая рестарт/redeploy) —
# оба шага ниже идемпотентны, поэтому безопасно гонять их каждый раз, а не
# только при первом запуске.
set -e

echo "[entrypoint] Применяю миграции БД..."
node scripts/migrate-mysql.mjs

# Бутстрап первого админа — только если реально заданы обе переменные.
# Сам bootstrap-admin.mjs идемпотентен (ничего не делает, если admin уже
# есть), но требует обе переменные ПОД УГРОЗОЙ ОШИБКИ — если их убрать из
# .env после первоначальной настройки (что нормально, они больше не нужны),
# контейнер не должен из-за этого падать при каждом обычном рестарте.
if [ -n "$BOOTSTRAP_ADMIN_EMAIL" ] && [ -n "$BOOTSTRAP_ADMIN_PASSWORD" ]; then
  echo "[entrypoint] Проверяю первого администратора..."
  node scripts/bootstrap-admin.mjs
else
  echo "[entrypoint] BOOTSTRAP_ADMIN_EMAIL/PASSWORD не заданы — пропускаю (нормально, если админ уже создан)."
fi

echo "[entrypoint] Запускаю сервер..."
exec pnpm start
