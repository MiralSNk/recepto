import { describe, it, expect } from 'vitest';
import { formatMessage } from '@/lib/shared/chat-utils';

/**
 * Регрессионные тесты на закрытую проблему: в formatMessage() автоссылки на
 * внутренние пути (шаг 2) раньше выполнялись поверх уже готовой HTML-
 * разметки markdown-ссылок (шаг 1) без проверки, что путь лежит внутри уже
 * вставленного <a>. Если видимый текст markdown-ссылки `[текст](url)` сам
 * содержал что-то похожее на внутренний путь ("/rooms/5" и т.п.),
 * автоссылочный regex оборачивал этот кусок текста в отдельный вложенный
 * <a>...</a> внутри уже существующего <a> — невалидный HTML, из-за которого
 * браузер/DOMPurify закрывают внешний тег раньше времени, и часть текста
 * выпадает из ссылки.
 *
 * Сейчас formatMessage() строит linkRanges (диапазоны уже вставленных
 * <a>...</a>) и пропускает совпадения автоссылок внутри них — сообщение вида
 * "[Смотри /rooms/5 сейчас](/booking)" (так вполне может ответить ИИ-
 * консьерж — он прямо инструктируется отдавать markdown-ссылки с путями вида
 * /category/id) теперь даёт одну ссылку на /booking, а не две с разными href.
 */
describe('formatMessage — вложенные <a> при пути внутри текста ссылки (регресс-тест на исправленный баг)', () => {
  it('не создаёт вложенный <a> внутри текста markdown-ссылки', () => {
    const html = formatMessage('[Смотри /rooms/5 сейчас](/booking)');

    // Открывающих тегов <a ...> не должно быть больше одного.
    const openTags = html.match(/<a [^>]*>/g) || [];
    expect(openTags.length).toBe(1);
  });

  it('весь текст ссылки указывает на один и тот же href (/booking)', () => {
    const html = formatMessage('[Смотри /rooms/5 сейчас](/booking)');

    expect(html).toBe(
      '<a href="/booking" class="chat-widget__link">Смотри /rooms/5 сейчас</a>'
    );
  });
});
