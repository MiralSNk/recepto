import { createRateLimiter } from '@/lib/server/rate-limit';

// Общий лимитер для /api/admin-recovery/verify И /api/admin-recovery/reset —
// один и тот же модульный instance (единый бюджет попыток), чтобы reset
// нельзя было дёргать напрямую в обход исчерпанного лимита verify.
//
// Намеренно ГЛОБАЛЬНЫЙ счётчик, не по IP: X-Forwarded-For на границе
// Node/Next.js — заголовок, полностью управляемый клиентом, если перед
// приложением нет реверс-прокси с известной здесь схемой доверенных хопов.
// Ранее ключом лимитера был IP из этого заголовка — атакующий тривиально
// обходил лимит, подставляя новое значение на каждый запрос (лимитер видел
// "нового клиента" каждый раз и никогда не отдавал 429). У этого потока нет
// и email как дополнительного ключа (в этом весь смысл recovery без email) —
// единственный надёжный вариант — считать попытки суммарно, а не "по
// клиенту". Цена: чужой перебор временно исчерпывает лимит и для настоящего
// админа — приемлемо для редко используемого recovery-флоу, когда
// альтернатива — брутфорс секретного слова без всякого ограничения.
const checkGlobalAdminRecoveryRateLimit = createRateLimiter(5, 15 * 60_000);
const GLOBAL_KEY = 'admin-recovery';

export function checkAdminRecoveryRateLimit(): boolean {
  return checkGlobalAdminRecoveryRateLimit(GLOBAL_KEY);
}
